package io.github.helios57.protogen.compiler.gen;

import java.util.EnumSet;

/**
 * Emits the package-private {@code ProtoWire} codec for one Java package.
 * <p>
 * Every generated Java package gets its own copy, so packages never depend on one another - messages only
 * ever exchange {@code byte[]} and {@code int} across a package boundary. Only the helpers the package
 * actually uses are emitted.
 */
final class CodecEmitter {

    private final EnumSet<Feature> features;

    CodecEmitter(EnumSet<Feature> features) {
        this.features = features;
    }

    String emit(String javaPackage) {
        Java out = new Java();
        out.line("package " + javaPackage + ";");
        out.blank();
        out.line("import java.nio.charset.StandardCharsets;");
        out.line("import java.util.Arrays;");
        out.blank();
        out.javadoc("""
                Protobuf wire-format codec, generated by protogen. Do not edit.

                <p>This class is emitted as source rather than shipped as a jar - that is what makes protogen
                output self-contained. It imports nothing but {@code java.*}, and carries only the helpers the
                messages in this package actually use.""");
        out.line("final class ProtoWire {");
        out.indent();
        out.blank();
        out.line("private ProtoWire() {");
        out.line("}");

        emitWriters(out);
        emitSizes(out);
        emitZigZag(out);
        emitReader(out);

        out.outdent();
        out.line("}");
        return out.toString();
    }

    private void emitWriters(Java out) {
        if (features.contains(Feature.W_UVARINT32)) {
            out.blank();
            out.javadoc("Writes {@code value} as an unsigned varint. @return the new position");
            out.line("static int wUVarint32(byte[] b, int p, int value) {");
            out.indent();
            out.line("while ((value & ~0x7f) != 0) {");
            out.indent();
            out.line("b[p++] = (byte) ((value & 0x7f) | 0x80);");
            out.line("value >>>= 7;");
            out.outdent();
            out.line("}");
            out.line("b[p++] = (byte) value;");
            out.line("return p;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_VARINT64)) {
            out.blank();
            out.javadoc("Writes {@code value} as a varint, ten bytes when negative. @return the new position");
            out.line("static int wVarint64(byte[] b, int p, long value) {");
            out.indent();
            out.line("while ((value & ~0x7fL) != 0) {");
            out.indent();
            out.line("b[p++] = (byte) (((int) value & 0x7f) | 0x80);");
            out.line("value >>>= 7;");
            out.outdent();
            out.line("}");
            out.line("b[p++] = (byte) value;");
            out.line("return p;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_VARINT32)) {
            out.blank();
            out.javadoc("Writes an {@code int32}: negative values are sign-extended to ten bytes, as protoc does.");
            out.line("static int wVarint32(byte[] b, int p, int value) {");
            out.indent();
            out.line("return value >= 0 ? wUVarint32(b, p, value) : wVarint64(b, p, value);");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_FIXED32)) {
            out.blank();
            out.line("static int wFixed32(byte[] b, int p, int value) {");
            out.indent();
            out.line("b[p] = (byte) value;");
            out.line("b[p + 1] = (byte) (value >> 8);");
            out.line("b[p + 2] = (byte) (value >> 16);");
            out.line("b[p + 3] = (byte) (value >> 24);");
            out.line("return p + 4;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_FIXED64)) {
            out.blank();
            out.line("static int wFixed64(byte[] b, int p, long value) {");
            out.indent();
            out.line("b[p] = (byte) value;");
            out.line("b[p + 1] = (byte) (value >> 8);");
            out.line("b[p + 2] = (byte) (value >> 16);");
            out.line("b[p + 3] = (byte) (value >> 24);");
            out.line("b[p + 4] = (byte) (value >> 32);");
            out.line("b[p + 5] = (byte) (value >> 40);");
            out.line("b[p + 6] = (byte) (value >> 48);");
            out.line("b[p + 7] = (byte) (value >> 56);");
            out.line("return p + 8;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_STRING)) {
            out.blank();
            out.javadoc("Writes a length-prefixed UTF-8 string.");
            out.line("static int wString(byte[] b, int p, String value) {");
            out.indent();
            out.line("byte[] utf8 = value.getBytes(StandardCharsets.UTF_8);");
            out.line("p = wUVarint32(b, p, utf8.length);");
            out.line("System.arraycopy(utf8, 0, b, p, utf8.length);");
            out.line("return p + utf8.length;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.W_BYTES)) {
            out.blank();
            out.javadoc("Writes a length-prefixed byte string.");
            out.line("static int wBytes(byte[] b, int p, byte[] value) {");
            out.indent();
            out.line("p = wUVarint32(b, p, value.length);");
            out.line("System.arraycopy(value, 0, b, p, value.length);");
            out.line("return p + value.length;");
            out.outdent();
            out.line("}");
        }
    }

    private void emitSizes(Java out) {
        if (features.contains(Feature.S_UVARINT32)) {
            out.blank();
            out.line("static int sUVarint32(int value) {");
            out.indent();
            out.line("if ((value & (~0 << 7)) == 0) {");
            out.line("    return 1;");
            out.line("}");
            out.line("if ((value & (~0 << 14)) == 0) {");
            out.line("    return 2;");
            out.line("}");
            out.line("if ((value & (~0 << 21)) == 0) {");
            out.line("    return 3;");
            out.line("}");
            out.line("if ((value & (~0 << 28)) == 0) {");
            out.line("    return 4;");
            out.line("}");
            out.line("return 5;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.S_VARINT32)) {
            out.blank();
            out.javadoc("Encoded size of an {@code int32}; negative values are sign-extended to ten bytes.");
            out.line("static int sVarint32(int value) {");
            out.indent();
            out.line("if (value < 0) {");
            out.line("    return 10;");
            out.line("}");
            if (features.contains(Feature.S_UVARINT32)) {
                out.line("return sUVarint32(value);");
            } else {
                out.line("if ((value & (~0 << 7)) == 0) {");
                out.line("    return 1;");
                out.line("}");
                out.line("if ((value & (~0 << 14)) == 0) {");
                out.line("    return 2;");
                out.line("}");
                out.line("if ((value & (~0 << 21)) == 0) {");
                out.line("    return 3;");
                out.line("}");
                out.line("if ((value & (~0 << 28)) == 0) {");
                out.line("    return 4;");
                out.line("}");
                out.line("return 5;");
            }
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.S_VARINT64)) {
            out.blank();
            out.line("static int sVarint64(long value) {");
            out.indent();
            out.line("if (value < 0) {");
            out.line("    return 10;");
            out.line("}");
            out.line("int n = 1;");
            out.line("while ((value >>>= 7) != 0) {");
            out.line("    n++;");
            out.line("}");
            out.line("return n;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.UTF8_LEN)) {
            out.blank();
            out.javadoc("""
                    Length of the UTF-8 encoding of {@code s}, computed without allocating it.

                    <p>Must agree byte for byte with {@code String.getBytes(UTF_8)}, which replaces an
                    unpaired surrogate with a single {@code '?'} - counting it as three bytes would leave a
                    gap in the output buffer and corrupt every following field.""");
            out.line("static int utf8Len(String s) {");
            out.indent();
            out.line("int len = s.length();");
            out.line("int bytes = 0;");
            out.line("for (int i = 0; i < len; i++) {");
            out.indent();
            out.line("char c = s.charAt(i);");
            out.line("if (c < 0x80) {");
            out.line("    bytes += 1;");
            out.line("} else if (c < 0x800) {");
            out.line("    bytes += 2;");
            out.line("} else if (Character.isHighSurrogate(c) && i + 1 < len && Character.isLowSurrogate(s.charAt(i + 1))) {");
            out.line("    bytes += 4;");
            out.line("    i++;");
            out.line("} else if (Character.isSurrogate(c)) {");
            out.line("    bytes += 1; // unpaired surrogate, encoded as '?'");
            out.line("} else {");
            out.line("    bytes += 3;");
            out.line("}");
            out.outdent();
            out.line("}");
            out.line("return bytes;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.S_STRING)) {
            out.blank();
            out.javadoc("Encoded size of a length-prefixed UTF-8 string.");
            out.line("static int sString(String value) {");
            out.indent();
            out.line("int n = utf8Len(value);");
            out.line("return sUVarint32(n) + n;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.S_BYTES)) {
            out.blank();
            out.line("static int sBytes(byte[] value) {");
            out.indent();
            out.line("return sUVarint32(value.length) + value.length;");
            out.outdent();
            out.line("}");
        }
    }

    private void emitZigZag(Java out) {
        if (features.contains(Feature.ZIGZAG32)) {
            out.blank();
            out.line("static int zz32(int n) {");
            out.line("    return (n << 1) ^ (n >> 31);");
            out.line("}");
            out.blank();
            out.line("static int unZz32(int n) {");
            out.line("    return (n >>> 1) ^ -(n & 1);");
            out.line("}");
        }
        if (features.contains(Feature.ZIGZAG64)) {
            out.blank();
            out.line("static long zz64(long n) {");
            out.line("    return (n << 1) ^ (n >> 63);");
            out.line("}");
            out.blank();
            out.line("static long unZz64(long n) {");
            out.line("    return (n >>> 1) ^ -(n & 1);");
            out.line("}");
        }
    }

    private void emitReader(Java out) {
        out.blank();
        out.javadoc("""
                Cursor over a byte array. Not thread safe.

                <p>Malformed input raises {@link IllegalArgumentException}; keeping the exception type from
                {@code java.lang} is what lets generated code stay free of any shared runtime type.""");
        out.line("static final class R {");
        out.indent();
        out.blank();
        out.line("private final byte[] b;");
        out.line("private int p;");
        out.line("private int end;");
        out.blank();
        out.line("R(byte[] b, int off, int end) {");
        out.indent();
        out.line("this.b = b;");
        out.line("this.p = off;");
        out.line("this.end = end;");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("boolean isAtEnd() {");
        out.line("    return p >= end;");
        out.line("}");

        out.blank();
        out.javadoc("@return the next tag, or 0 at the end of the current limit");
        out.line("int tag() {");
        out.indent();
        out.line("if (p >= end) {");
        out.line("    return 0;");
        out.line("}");
        out.line("int tag = uvarint32();");
        out.line("if ((tag >>> 3) == 0) {");
        out.line("    throw malformed(\"field number 0\");");
        out.line("}");
        out.line("return tag;");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("int uvarint32() {");
        out.indent();
        out.line("int result = 0;");
        out.line("for (int shift = 0; shift < 32; shift += 7) {");
        out.indent();
        out.line("int c = rawByte();");
        out.line("result |= (c & 0x7f) << shift;");
        out.line("if ((c & 0x80) == 0) {");
        out.line("    return result;");
        out.line("}");
        out.outdent();
        out.line("}");
        out.line("// value was sign-extended from int64; drop the remaining continuation bytes");
        out.line("for (int i = 0; i < 5; i++) {");
        out.indent();
        out.line("if ((rawByte() & 0x80) == 0) {");
        out.line("    return result;");
        out.line("}");
        out.outdent();
        out.line("}");
        out.line("throw malformed(\"varint32 longer than ten bytes\");");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("long varint64() {");
        out.indent();
        out.line("long result = 0;");
        out.line("for (int shift = 0; shift < 64; shift += 7) {");
        out.indent();
        out.line("int c = rawByte();");
        out.line("result |= (long) (c & 0x7f) << shift;");
        out.line("if ((c & 0x80) == 0) {");
        out.line("    return result;");
        out.line("}");
        out.outdent();
        out.line("}");
        out.line("throw malformed(\"varint64 longer than ten bytes\");");
        out.outdent();
        out.line("}");

        if (features.contains(Feature.R_BOOL)) {
            out.blank();
            out.line("boolean bool() {");
            out.line("    return varint64() != 0L;");
            out.line("}");
        }
        if (features.contains(Feature.R_FIXED32)) {
            out.blank();
            out.line("int fixed32() {");
            out.indent();
            out.line("require(4);");
            out.line("int v = (b[p] & 0xff) | ((b[p + 1] & 0xff) << 8) | ((b[p + 2] & 0xff) << 16) | ((b[p + 3] & 0xff) << 24);");
            out.line("p += 4;");
            out.line("return v;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.R_FIXED64)) {
            out.blank();
            out.line("long fixed64() {");
            out.indent();
            out.line("require(8);");
            out.line("long v = (b[p] & 0xffL) | ((b[p + 1] & 0xffL) << 8) | ((b[p + 2] & 0xffL) << 16)");
            out.line("        | ((b[p + 3] & 0xffL) << 24) | ((b[p + 4] & 0xffL) << 32) | ((b[p + 5] & 0xffL) << 40)");
            out.line("        | ((b[p + 6] & 0xffL) << 48) | ((b[p + 7] & 0xffL) << 56);");
            out.line("p += 8;");
            out.line("return v;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.R_STRING)) {
            out.blank();
            out.line("String string() {");
            out.indent();
            out.line("int len = uvarint32();");
            out.line("require(len);");
            out.line("String s = new String(b, p, len, StandardCharsets.UTF_8);");
            out.line("p += len;");
            out.line("return s;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.R_BYTES)) {
            out.blank();
            out.line("byte[] bytes() {");
            out.indent();
            out.line("int len = uvarint32();");
            out.line("require(len);");
            out.line("byte[] out = Arrays.copyOfRange(b, p, p + len);");
            out.line("p += len;");
            out.line("return out;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.R_SLICE)) {
            out.blank();
            out.javadoc("@return the backing array, so a submessage can be parsed in place");
            out.line("byte[] array() {");
            out.line("    return b;");
            out.line("}");
            out.blank();
            out.javadoc("Consumes {@code len} bytes. @return the offset they start at");
            out.line("int slice(int len) {");
            out.indent();
            out.line("require(len);");
            out.line("int start = p;");
            out.line("p += len;");
            out.line("return start;");
            out.outdent();
            out.line("}");
        }
        if (features.contains(Feature.R_LIMIT)) {
            out.blank();
            out.javadoc("Restricts reading to the next {@code len} bytes. @return the previous limit");
            out.line("int pushLimit(int len) {");
            out.indent();
            out.line("require(len);");
            out.line("int old = end;");
            out.line("end = p + len;");
            out.line("return old;");
            out.outdent();
            out.line("}");
            out.blank();
            out.line("void popLimit(int old) {");
            out.line("    end = old;");
            out.line("}");
        }

        out.blank();
        out.javadoc("Skips the payload of an unknown or unexpected field.");
        out.line("void skip(int tag) {");
        out.indent();
        out.line("switch (tag & 7) {");
        out.indent();
        out.line("case 0 -> varint64();");
        out.line("case 1 -> advance(8);");
        out.line("case 2 -> advance(uvarint32());");
        out.line("case 5 -> advance(4);");
        out.line("default -> throw malformed(\"unsupported wire type \" + (tag & 7));");
        out.outdent();
        out.line("}");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("private void advance(int n) {");
        out.indent();
        out.line("require(n);");
        out.line("p += n;");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("private int rawByte() {");
        out.indent();
        out.line("require(1);");
        out.line("return b[p++];");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("private void require(int n) {");
        out.indent();
        out.line("if (n < 0 || p + n > end) {");
        out.indent();
        out.line("throw malformed(\"truncated message: need \" + n + \" byte(s) at offset \" + p");
        out.line("        + \" but only \" + (end - p) + \" remain\");");
        out.outdent();
        out.line("}");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("private IllegalArgumentException malformed(String detail) {");
        out.line("    return new IllegalArgumentException(\"malformed protobuf input: \" + detail);");
        out.line("}");

        out.outdent();
        out.line("}");
    }
}
