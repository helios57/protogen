package io.github.helios57.protogen.compiler.gen;

import io.github.helios57.protogen.compiler.linker.Schema;
import io.github.helios57.protogen.compiler.model.Defs;
import io.github.helios57.protogen.compiler.model.ProtoFile;

import java.util.ArrayList;
import java.util.EnumSet;
import java.util.List;

/** Turns a linked {@link Schema} into self-contained Java source files. */
public final class JavaGenerator {

    /**
     * One generated Java source file.
     *
     * @param relativePath path relative to the output directory, e.g. {@code com/example/Foo.java}
     * @param content      the full source text
     */
    public record GeneratedFile(String relativePath, String content) {
    }

    private final boolean emitJavadoc;

    public JavaGenerator(boolean emitJavadoc) {
        this.emitJavadoc = emitJavadoc;
    }

    /** Generates every file for the schema, including one {@code ProtoWire} per Java package. */
    public List<GeneratedFile> generate(Schema schema) {
        List<GeneratedFile> out = new ArrayList<>();
        for (String javaPackage : schema.javaPackages()) {
            List<ProtoFile> files = schema.filesIn(javaPackage);

            EnumSet<Feature> features = Feature.of(files);
            out.add(new GeneratedFile(path(javaPackage, "ProtoWire"),
                    new CodecEmitter(features).emit(javaPackage)));

            for (ProtoFile file : files) {
                out.addAll(generate(file, javaPackage));
            }
        }
        return out;
    }

    private List<GeneratedFile> generate(ProtoFile file, String javaPackage) {
        List<GeneratedFile> out = new ArrayList<>();
        MessageEmitter messages = new MessageEmitter(javaPackage, emitJavadoc);
        EnumEmitter enums = new EnumEmitter(emitJavadoc);

        if (file.javaMultipleFiles()) {
            for (Defs.EnumDef def : file.enums()) {
                Java java = header(javaPackage, file);
                enums.emit(java, def, true);
                out.add(new GeneratedFile(path(javaPackage, def.name()), java.toString()));
            }
            for (Defs.MessageDef def : file.messages()) {
                Java java = header(javaPackage, file);
                messages.emit(java, def, true);
                out.add(new GeneratedFile(path(javaPackage, def.name()), java.toString()));
            }
            return out;
        }

        String outer = file.javaOuterClassName();
        Java java = header(javaPackage, file);
        if (emitJavadoc) {
            java.javadoc("Types generated from {@code " + file.fileName() + "}.");
        }
        java.line("public final class " + outer + " {");
        java.indent();
        java.blank();
        java.line("private " + outer + "() {");
        java.line("}");
        for (Defs.EnumDef def : file.enums()) {
            java.blank();
            enums.emit(java, def, false);
        }
        for (Defs.MessageDef def : file.messages()) {
            java.blank();
            messages.emit(java, def, false);
        }
        java.outdent();
        java.line("}");
        out.add(new GeneratedFile(path(javaPackage, outer), java.toString()));
        return out;
    }

    private Java header(String javaPackage, ProtoFile file) {
        Java java = new Java();
        if (!javaPackage.isEmpty()) {
            java.line("package " + javaPackage + ";");
            java.blank();
        }
        java.line("// Generated by protogen from " + file.fileName() + ". Do not edit.");
        java.blank();
        return java;
    }

    private static String path(String javaPackage, String className) {
        String dir = javaPackage.isEmpty() ? "" : javaPackage.replace('.', '/') + "/";
        return dir + className + ".java";
    }
}
